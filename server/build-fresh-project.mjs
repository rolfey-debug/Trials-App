#!/usr/bin/env node
/**
 * Generate server/fresh-project.sql — `npm run sql:fresh`.
 *
 * One paste-and-run file that takes a brand-new Supabase project to the full
 * current state: schema v2 + RLS + seeds (001, which already carries the 002
 * current_org fix), the Ringwood site/trial (003), and the invite-only signup
 * lockdown (004). 004 `create or replace`s the signup trigger function and
 * drops the bucket policy 001 created, so plain concatenation is correct.
 *
 * Written for the region move: Supabase pins a project's region at creation,
 * so relocating to Sydney means a new project, and a new project should never
 * exist for a moment with open signup — this file closes it in the same paste.
 *
 * Generated file; edit the migrations, then re-run this script.
 */

import { readFile, writeFile } from 'node:fs/promises'

const PARTS = [
  'server/migrations/001_init.sql',
  'server/migrations/003_ringwood.sql',
  'server/migrations/004_close_open_signup.sql',
]

const HEADER = `-- ===========================================================================
-- AGnVET Trial Work — fresh project setup (generated by \`npm run sql:fresh\`,
-- do not edit: change server/migrations/ and regenerate).
--
-- Paste the WHOLE file into the new project's SQL editor and run once.
-- It is migrations 001 + 003 + 004 in order: full schema, RLS, seeds, and
-- the invite-only signup lockdown — the new project is never open.
--
-- >>> ONE EDIT BEFORE RUNNING: the INVITED PEOPLE block at the very end. <<<
--
-- Afterwards, in the dashboard (SQL cannot reach these):
--   1. Authentication -> Sign In / Up -> turn OFF "Allow new users to sign up".
--   2. (Optional) leave "Confirm email" off for a smoother first sign-in.
-- ===========================================================================

`

const FOOTER = `
-- ===========================================================================
-- INVITED PEOPLE — >>> EDIT THIS LIST, THEN RUN <<<
--
-- One row per person allowed to sign in. Roles: admin | agronomist | team |
-- grower | rep. Anyone not listed here cannot become an org member even if
-- they somehow create an auth account.
-- ===========================================================================

insert into allowed_signups (email, org_id, role, invited_by) values
  ('andrewrolfe@agnvet.com.au', '00000000-0000-0000-0000-000000000001', 'admin', 'setup')
  -- , ('colleague@agnvet.com.au', '00000000-0000-0000-0000-000000000001', 'agronomist', 'setup')
on conflict (email) do nothing;

select email, role from allowed_signups order by email;
`

const chunks = await Promise.all(
  PARTS.map(async (p) => `-- ────────────────── from ${p} ──────────────────\n\n${await readFile(p, 'utf8')}`),
)
await writeFile('server/fresh-project.sql', HEADER + chunks.join('\n\n') + FOOTER)
console.log(`server/fresh-project.sql ← ${PARTS.join(' + ')}`)
